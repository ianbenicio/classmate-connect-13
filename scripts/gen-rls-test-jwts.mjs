#!/usr/bin/env node
/**
 * gen-rls-test-jwts.mjs — Sign in test users and print their access JWTs.
 *
 * Required env:
 *   VITE_SUPABASE_URL              (or SUPABASE_URL)
 *   VITE_SUPABASE_PUBLISHABLE_KEY  (or SUPABASE_ANON_KEY)
 *
 * Per-role credentials (email + password) — set for each role you want a JWT for:
 *   RLS_TEST_ALUNO_EMAIL       RLS_TEST_ALUNO_PASSWORD
 *   RLS_TEST_PROFESSOR_EMAIL   RLS_TEST_PROFESSOR_PASSWORD
 *   RLS_TEST_ADMIN_EMAIL       RLS_TEST_ADMIN_PASSWORD
 *   RLS_TEST_SUPER_EMAIL       RLS_TEST_SUPER_PASSWORD   (optional)
 *
 * Output: writes RLS_TEST_*_JWT lines to stdout in dotenv format.
 *   node scripts/gen-rls-test-jwts.mjs > .env.test.local
 *
 * Tokens are short-lived (default 1h). Re-run before each smoke session.
 * Test users must already exist with these credentials.
 */
import { createClient } from "@supabase/supabase-js";

const url = process.env.VITE_SUPABASE_URL ?? process.env.SUPABASE_URL ?? "";
const anonKey =
  process.env.VITE_SUPABASE_PUBLISHABLE_KEY ?? process.env.SUPABASE_ANON_KEY ?? "";

if (!url || !anonKey) {
  console.error("[gen-rls-test-jwts] missing VITE_SUPABASE_URL or VITE_SUPABASE_PUBLISHABLE_KEY");
  process.exit(2);
}

const roles = [
  { key: "ALUNO", emailEnv: "RLS_TEST_ALUNO_EMAIL", passEnv: "RLS_TEST_ALUNO_PASSWORD" },
  { key: "PROFESSOR", emailEnv: "RLS_TEST_PROFESSOR_EMAIL", passEnv: "RLS_TEST_PROFESSOR_PASSWORD" },
  { key: "ADMIN", emailEnv: "RLS_TEST_ADMIN_EMAIL", passEnv: "RLS_TEST_ADMIN_PASSWORD" },
  { key: "SUPER", emailEnv: "RLS_TEST_SUPER_EMAIL", passEnv: "RLS_TEST_SUPER_PASSWORD" },
];

async function signIn(email, password) {
  const c = createClient(url, anonKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const { data, error } = await c.auth.signInWithPassword({ email, password });
  if (error) return { error };
  return { token: data.session?.access_token ?? null };
}

let exitCode = 0;
const out = [`# Generated by scripts/gen-rls-test-jwts.mjs at ${new Date().toISOString()}`];

for (const r of roles) {
  const email = process.env[r.emailEnv];
  const password = process.env[r.passEnv];
  if (!email || !password) {
    if (r.key === "SUPER") {
      console.error(`[skip] ${r.key}: ${r.emailEnv}/${r.passEnv} not set (optional)`);
      continue;
    }
    console.error(`[skip] ${r.key}: ${r.emailEnv}/${r.passEnv} not set`);
    continue;
  }
  const { token, error } = await signIn(email, password);
  if (error || !token) {
    console.error(`[fail] ${r.key} (${email}): ${error?.message ?? "no token"}`);
    exitCode = 1;
    continue;
  }
  out.push(`RLS_TEST_${r.key}_JWT=${token}`);
  console.error(`[ok] ${r.key} (${email})`);
}

console.log(out.join("\n"));
process.exit(exitCode);
